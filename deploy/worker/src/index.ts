/* -------------------------------------------------------------- auth ----- */

async function sha256Hex(value: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(value));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** Constant-time compare, so a wrong token cannot be found byte by byte. */
function timingSafeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i += 1) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

async function authenticate(request: Request, env: Env): Promise<Caller | null> {
  const header = request.headers.get("authorization") ?? "";
  if (!header.startsWith("Bearer ")) return null;
  const presented = header.slice(7).trim();
  if (!presented) return null;

  const hash = await sha256Hex(presented);
  const row = await env.DB.prepare(
    `SELECT label, scopes, expires_at, revoked_at, rate_per_minute, rate_per_day
       FROM tokens WHERE token_sha256 = ?`,
  )
    .bind(hash)
    .first<{
      label: string;
      scopes: string;
      expires_at: string | null;
      revoked_at: string | null;
      rate_per_minute: number | null;
      rate_per_day: number | null;
    }>();

  if (row) {
    if (row.revoked_at) return null;
    if (row.expires_at && new Date(row.expires_at) < new Date()) return null;
    // Usage is recorded so an unused or runaway token is visible later.
    await env.DB.prepare(
      `UPDATE tokens SET last_used_at = ?, call_count = call_count + 1
         WHERE token_sha256 = ?`,
    )
      .bind(new Date().toISOString(), hash)
      .run();
    return {
      label: row.label,
      scopes: new Set(row.scopes.split(/[,\s]+/).filter(Boolean)),
      quotaKey: hash,
      limits: limitsFor(row),
    };
  }

  if (env.BOOTSTRAP_TOKEN && timingSafeEqual(presented, env.BOOTSTRAP_TOKEN)) {
    return { label: "bootstrap", scopes: new Set(["read", "context"]), quotaKey: "bootstrap", limits: limitsFor({}) };
  }
  return null;
}

/* ------------------------------------------------------------ quotas ----- */

function quotaStore(env: Env, key: string): QuotaStore {
  return {
    async take(bucket, limit) {
      // One statement: the row is created at 1, or incremented only while below the
      // limit. When the WHERE fails nothing is updated and nothing is returned.
      const row = await env.DB.prepare(
        `INSERT INTO token_usage (token_sha256, bucket, count) VALUES (?, ?, 1)
           ON CONFLICT (token_sha256, bucket) DO UPDATE SET count = count + 1
           WHERE count < ?
         RETURNING count`,
      )
        .bind(key, bucket, limit)
        .first<{ count: number }>();
      return row !== null;
    },
    async reject(dayBucket) {
      await env.DB.prepare(
        `INSERT INTO token_usage (token_sha256, bucket, count, rejected) VALUES (?, ?, 0, 1)
           ON CONFLICT (token_sha256, bucket) DO UPDATE SET rejected = rejected + 1`,
      )
        .bind(key, dayBucket)
        .run();
    },
  };
}

/**
 * Count one call against the caller's quotas. Null means go ahead; otherwise the
 * response to send instead. `id` is the JSON-RPC id, or undefined for a non-RPC path.
 *
 * A quota that cannot be checked refuses the call rather than waving it through:
 * the database it needs is the one every lookup needs too.
 */
async function enforceQuota(env: Env, caller: Caller, id?: unknown): Promise<Response | null> {
  let decision: QuotaDecision;
  try {
    decision = await checkQuota(quotaStore(env, caller.quotaKey), caller.limits, new Date());
  } catch {
    return refusal(id, 503, QUOTA_UNAVAILABLE, "quota check unavailable; nothing was looked up", {
      reason: "quota_unavailable",
      retry_after_seconds: 30,
    });
  }
  if (decision.allowed) return null;
  return refusal(id, 429, RATE_LIMITED, `rate limit exceeded: ${decision.limit} calls per ${decision.scope}`, {
    reason: "rate_limited",
    scope: decision.scope,
    limit: decision.limit,
    retry_after_seconds: decision.retryAfterSeconds,
  });
}

function refusal(id: unknown, status: number, code: number, message: string, data: Json): Response {
  const headers = { "retry-after": String(data.retry_after_seconds) };
  const body = id === undefined ? { error: data.reason, message, ...data } : { jsonrpc: "2.0", id, error: { code, message, data } };
  return Response.json(body, { status, headers });
}

/* ------------------------------------------------------------- shaping --- */

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

function validDate(value: unknown): string | null {
  return typeof value === "string" && DATE_RE.test(value) ? value : null;
}

function clampLimit(value: unknown): number {
  const n = typeof value === "number" ? Math.floor(value) : DEFAULT_LIMIT;
  return Math.min(Math.max(n, 1), MAX_LIMIT);
}

/**
 * The registry-controlled tail of a host, by the publicsuffix.org algorithm:
 * the rule matching the most labels wins, an exception beats a wildcard, and an
 * unlisted TLD falls back to the implicit `*` rule so a novel TLD does not make
 * the whole host look registrable.
 */
function publicSuffix(labels: string[]): string {
  for (let i = 0; i < labels.length; i += 1) {
    const candidate = labels.slice(i).join(".");
    if (PSL_EXCEPTION.has(candidate)) return labels.slice(i + 1).join(".");
    const parent = labels.slice(i + 1).join(".");
    if (parent && PSL_WILDCARD.has(parent)) return candidate;
    if (PSL_NORMAL.has(candidate)) return candidate;
  }
  return labels[labels.length - 1];
}

/**
 * A log names the host that actually resolved, which is often a child of the
 * host the report named, so `a.b.evil.com` has to still find `evil.com`.
 *
 * Parents stop at the registrable domain. Walking all the way down produced
 * `co.uk` and `github.io` as lookup keys, and a report that named either would
 * then match every unrelated tenant beneath it. Nothing at or above the public
 * suffix belongs to anyone in particular, so nothing there is a useful key.
 */
function hostCandidates(value: string): string[] {
  const host = value.trim().toLowerCase().replace(/\.$/, "");
  if (!host.includes(".") || /^[\d.]+$/.test(host)) return [host];
  const labels = host.split(".");
  const suffixLength = publicSuffix(labels).split(".").length;
  const out: string[] = [];
  for (let i = 0; i <= labels.length - suffixLength - 1; i += 1) {
    out.push(labels.slice(i).join("."));
  }
  // The host is itself a public suffix, so it has no registrable parent. Look
  // it up verbatim rather than returning nothing.
  return out.length ? out : [host];
}

function rowToHit(row: Json, caller: Caller): Json {
  const hit: Json = {
    report_date: row.report_date,
    indicator_type: row.indicator_type,
    value: row.value,
    status: row.status,
    action: row.action,
    priority: row.priority,
    reason: row.reason,
    kev: row.kev === null || row.kev === undefined ? null : Boolean(row.kev),
    kev_due_date: row.kev_due_date,
    cvss_score: row.cvss_score,
    cvss_severity: row.cvss_severity,
    source: row.source,
    article_title: row.article_title,
    article_url: row.article_url,
    section: row.section,
    // Names the rule that kept this off the block list, when one did. The
    // reason string beside it is Chinese prose; a consumer deciding whether a
    // hit is a public resolver or a registry boundary should not have to match
    // substrings of it.
    benign_basis: row.benign_basis ?? null,
    epss_score: row.epss_score ?? null,
    epss_percentile: row.epss_percentile ?? null,
  };
  // The context line is a verbatim source sentence. A token without the scope
  // gets the citation and can read it at the publisher.
  if (caller.scopes.has("context")) hit.context = row.context ?? null;
  return hit;
}

