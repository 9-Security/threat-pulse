// Generated by `npm run psl` from the same list the Python package bundles, so
// the boundary a report was written against matches the one a query uses.
const PSL_NORMAL = new Set(pslRules.normal);
const PSL_WILDCARD = new Set(pslRules.wildcard);
const PSL_EXCEPTION = new Set(pslRules.exception);

