async function listReports(env: Env, args: Json): Promise<Json> {
  const { results } = await env.DB.prepare(
    `SELECT report_date, subject, article_count, confirmed_ioc_count,
            patch_count, block_count, hunt_count, kev_count, unavailable_count,
            generated_at
       FROM reports ORDER BY report_date DESC LIMIT ?`,
  )
    .bind(clampLimit(args.limit))
    .all<Json>();
  return { count: results.length, reports: results };
}

async function reportSummary(env: Env, args: Json): Promise<Json> {
  const date = validDate(args.date);
  const row = date
    ? await env.DB.prepare(`SELECT * FROM reports WHERE report_date = ?`).bind(date).first<Json>()
    : await env.DB.prepare(`SELECT * FROM reports ORDER BY report_date DESC LIMIT 1`).first<Json>();
  if (!row) return { error: date ? `no report for ${date}` : "no reports ingested yet" };
  let enrichment: unknown = null;
  try {
    enrichment = JSON.parse(String(row.enrichment_json ?? "{}"));
  } catch {
    enrichment = null;
  }
  const { enrichment_json, ...rest } = row;
  return { ...rest, enrichment };
}

async function searchIocs(env: Env, args: Json, caller: Caller): Promise<Json> {
  const clauses: string[] = ["status = 'confirmed'"];
  const binds: unknown[] = [];
  const date = validDate(args.date);
  const since = validDate(args.since);
  if (date) {
    clauses.push("report_date = ?");
    binds.push(date);
  } else if (since) {
    clauses.push("report_date >= ?");
    binds.push(since);
  }
  if (typeof args.action === "string" && args.action) {
    clauses.push("action = ?");
    binds.push(args.action.toLowerCase());
  }
  if (typeof args.indicator_type === "string" && args.indicator_type) {
    clauses.push("indicator_type = ?");
    binds.push(args.indicator_type.toLowerCase());
  }
  if (typeof args.query === "string" && args.query.trim()) {
    // A pasted private address or internal name is refused before it reaches a
    // query. Plain words are search terms and pass.
    const refused = classifySearchText(args.query);
    if (refused) return { status: "skipped", reason: refused, count: 0, truncated: false, items: [] };
    clauses.push("(value LIKE ? OR article_title LIKE ? OR reason LIKE ?)");
    const like = `%${args.query.trim()}%`;
    binds.push(like, like, like);
  }
  const limit = clampLimit(args.limit);
  // One row past the limit is fetched so `truncated` says whether rows were left
  // out, rather than only that the limit was reached.
  const { results } = await env.DB.prepare(
    `SELECT * FROM indicators WHERE ${clauses.join(" AND ")}
      ORDER BY report_date DESC, indicator_type, value LIMIT ?`,
  )
    .bind(...binds, limit + 1)
    .all<Json>();
  const truncated = results.length > limit;
  const rows = truncated ? results.slice(0, limit) : results;
  return {
    status: truncated ? "partial" : "complete",
    count: rows.length,
    truncated,
    items: rows.map((row) => rowToHit(row, caller)),
  };
}

interface LookupOutcome {
  status: "complete" | "partial" | "failed";
  truncated: boolean;
  requested: number;
  items: Json[];
  skipped: Skipped[];
  errors: LookupError[];
}

/**
 * Look submitted values up. Skipping happens first, in guard.ts, so a private
 * address or internal hostname never reaches a statement; the rules for what counts
 * as looked up, failed or out of time live in lookup.ts, where they are tested
 * against a fake database. This function only supplies the real one.
 */
async function lookupMany(
  env: Env,
  values: unknown,
  since: string | null,
  caller: Caller,
): Promise<LookupOutcome> {
  const split = partition(values, MAX_BATCH);
  const { items, errors } = await lookupAccepted<Json>(split.accepted, {
    // A hash or CVE is matched as given; only hosts expand upward. The expansion
    // walks ~10,300 suffix rules, so it is computed only where it is used.
    expand: (value) =>
      /^[0-9a-f]{32,64}$/i.test(value) || /^cve-/i.test(value)
        ? [value.toLowerCase()]
        : hostCandidates(value),
    query: async (chunk) => {
      const binds: unknown[] = [...chunk];
      // value_lc is indexed; wrapping the column in LOWER() would force a scan.
      let sql = `SELECT * FROM indicators WHERE value_lc IN (${chunk.map(() => "?").join(",")})`;
      if (since) {
        sql += " AND report_date >= ?";
        binds.push(since);
      }
      sql += " ORDER BY report_date DESC";
      const { results } = await env.DB.prepare(sql).bind(...binds).all<Json>();
      return results;
    },
    keyOf: (row) => String(row.value).toLowerCase(),
    toHit: (row) => rowToHit(row, caller),
    heldBack: (row) => Boolean(row.benign_basis),
    now: () => Date.now(),
    budgetMs: LOOKUP_BUDGET_MS,
    // D1 allows 100 bound parameters per statement, and one hostname expands to a
    // candidate per label, so 40 FQDNs already overrun a single statement. 90 leaves
    // room for the date bound.
    chunkSize: 90,
  });
  return {
    status: statusOf(items.length, errors.length, split.truncated),
    truncated: split.truncated,
    requested: split.requested,
    items,
    skipped: split.skipped,
    errors,
  };
}

