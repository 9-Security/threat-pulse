const ENRICH_TYPES = OBSERVABLE_TYPES.map((kind) => `'${kind}'`).join(",");
const INDICATOR_FIELDS = `rowid AS rid, report_date, indicator_type, value, value_lc, action, priority,
  reason, benign_basis, source, article_title, article_url, published_at, context, registrable_lc`;

function enrichStore(env: Env): EnrichStore {
  const placeholders = (n: number) => new Array(n).fill("?").join(",");
  const sinceClause = (since: string | null) => (since ? " AND report_date >= ?" : "");
  const sinceBind = (since: string | null) => (since ? [since] : []);
  return {
    async indicators(keys, since) {
      // The unary + keeps SQLite off the indicator_type index. Without it the
      // planner switches at about sixteen keys and reads every row of those
      // types instead of seeking each value: measured 2026-09-23 on the live
      // database, 9 rows for 8 keys and 4,659 for 16. At the pilot's own quota
      // that is more than the daily row budget of the plan we are on.
      const { results } = await env.DB.prepare(
        `SELECT ${INDICATOR_FIELDS} FROM indicators
          WHERE value_lc IN (${placeholders(keys.length)}) AND +indicator_type IN (${ENRICH_TYPES})${sinceClause(since)}
          ORDER BY report_date, rowid`,
      )
        .bind(...keys, ...sinceBind(since))
        .all<IndicatorRow>();
      return results;
    },
    async children(registrables, since) {
      const { results } = await env.DB.prepare(
        `SELECT ${INDICATOR_FIELDS} FROM indicators
          WHERE registrable_lc IN (${placeholders(registrables.length)}) AND +indicator_type = 'domain'${sinceClause(since)}
          ORDER BY report_date, rowid`,
      )
        .bind(...registrables, ...sinceBind(since))
        .all<IndicatorRow>();
      return results;
    },
    async excluded(keys, since) {
      const { results } = await env.DB.prepare(
        `SELECT report_date, indicator_type, value, value_lc, reason_codes FROM excluded_values
          WHERE value_lc IN (${placeholders(keys.length)})${sinceClause(since)}
          ORDER BY report_date`,
      )
        .bind(...keys, ...sinceBind(since))
        .all<ExcludedRow>();
      return results;
    },
    async cveIntel(ids) {
      const { results } = await env.DB.prepare(
        `SELECT report_date, cve_id, record FROM cve_intel WHERE cve_id IN (${placeholders(ids.length)})`,
      )
        .bind(...ids)
        .all<CveRow>();
      return results;
    },
    async corpus(): Promise<CorpusInfo> {
      const [state, reports] = await env.DB.batch([
        env.DB.prepare(
          `SELECT corpus_version, days, first_date, last_date, publisher_count, psl_version
             FROM corpus_state WHERE id = 1`,
        ),
        env.DB.prepare(`SELECT report_date, report_id, sources_failed FROM reports ORDER BY report_date`),
      ]);
      return {
        state: ((state.results[0] as CorpusInfo["state"]) ?? null),
        reports: reports.results as CorpusInfo["reports"],
      };
    },
  };
}

/** The validator's suffix walk, over the same list the Worker already carries. */
const boundaries = {
  parents(host: string): string[] {
    const labels = host.split(".");
    const depth = publicSuffix(labels).split(".").length;
    const out: string[] = [];
    for (let i = 1; i < labels.length - depth; i += 1) out.push(labels.slice(i).join("."));
    return out;
  },
  registrable(host: string): string {
    const labels = host.split(".");
    const depth = publicSuffix(labels).split(".").length;
    return labels.length > depth ? labels.slice(-(depth + 1)).join(".") : host;
  },
};

async function enrich(env: Env, args: Json, caller: Caller): Promise<Json> {
  if (!Array.isArray(args.values) || !args.values.length) return { error: "values must be a non-empty array" };
  if (args.types !== undefined && (!Array.isArray(args.types) || args.types.length !== args.values.length)) {
    return { error: "types, when given, must be an array the same length as values" };
  }
  if (args.detail !== undefined && args.detail !== "compact" && args.detail !== "full") {
    return { error: "detail must be compact or full" };
  }
  if (args.since !== undefined && validDate(args.since) === null) return { error: "since must be YYYY-MM-DD" };
  return enrichObservables(
    {
      values: args.values,
      types: (args.types as unknown[] | undefined) ?? null,
      detail: args.detail as "compact" | "full" | undefined,
      since: validDate(args.since),
      mayReadContext: caller.scopes.has("context"),
    },
    {
      store: enrichStore(env),
      boundaries,
      now: () => Date.now(),
      requestId: () => crypto.randomUUID(),
      budgetMs: LOOKUP_BUDGET_MS,
      chunkSize: 90,
    },
  );
}

async function callTool(name: string, args: Json, env: Env, caller: Caller): Promise<Json> {
  switch (name) {
    case "list_reports":
      return listReports(env, args);
    case "get_report_summary":
      return reportSummary(env, args);
    case "search_confirmed_iocs":
      return searchIocs(env, args, caller);
    case "lookup_ioc": {
      if (typeof args.value !== "string" || !args.value.trim()) return { error: "value is required" };
      const outcome = await lookupMany(env, [args.value], validDate(args.since), caller);
      // A skipped or failed lookup carries no `found` field at all, so no caller
      // can read it as a miss.
      if (outcome.skipped.length) {
        const { value, reason } = outcome.skipped[0];
        return { status: "skipped", value, reason };
      }
      if (outcome.errors.length) {
        const { value, reason } = outcome.errors[0];
        return { status: "failed", value, reason };
      }
      return { status: "complete", ...outcome.items[0] };
    }
    case "lookup_iocs": {
      if (!Array.isArray(args.values) || !args.values.length) {
        return { error: "values must be a non-empty array" };
      }
      const outcome = await lookupMany(env, args.values, validDate(args.since), caller);
      const found = outcome.items.filter((i) => i.found).length;
      return {
        status: outcome.status,
        truncated: outcome.truncated,
        counts: {
          requested: outcome.requested,
          processed: outcome.items.length,
          skipped: outcome.skipped.length,
          failed: outcome.errors.length,
          found,
        },
        items: outcome.items,
        skipped: outcome.skipped,
        errors: outcome.errors,
        // Kept for callers written against the earlier response shape.
        requested: outcome.requested,
        examined: outcome.items.length,
        found,
      };
    }
    case "enrich_observables":
      return enrich(env, args, caller);
    default:
      return { error: `unknown tool: ${name}` };
  }
}

function rpcResult(id: unknown, result: unknown): Response {
  return Response.json({ jsonrpc: "2.0", id, result });
}

function rpcError(id: unknown, code: number, message: string, status = 200): Response {
  return Response.json({ jsonrpc: "2.0", id, error: { code, message } }, { status });
}

/* --------------------------------------------------------- heartbeat ----- */

/**
 * Ask D1 whether today's report arrived, and mail if it did not.
 *
 * Runs on a cron trigger rather than on the collecting host: a host that is off
 * or cut off cannot report that it is off. See heartbeat.ts for why this reads
 * the corpus instead of accepting a ping.
 *
 * Never throws. A scheduled handler that throws is retried and logged, and
 * neither does anything useful here -- the operator learns nothing from a
 * retried cron, and an exception loop would bury the one message that matters.
 */
async function readHeartbeatState(env: Env): Promise<HeartbeatState> {
  const row = await env.DB.prepare(
    `SELECT MAX(report_date) AS newest, COUNT(*) AS total FROM reports`,
  ).first<{ newest: string | null; total: number }>();
  return { newest: row?.newest ?? null, totalDays: Number(row?.total ?? 0) };
}

/** Never throws; the caller gets a description either way. */
async function sendAlertMail(env: Env, mail: { subject: string; body: string }): Promise<string> {
  if (!env.RESEND_API_KEY || !env.RESEND_FROM || !env.ALERT_TO) {
    // Loud, because in this state the alarm is armed and mute.
    return "not sent: RESEND_API_KEY, RESEND_FROM or ALERT_TO is unset on the Worker";
  }
  try {
    const response = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        authorization: `Bearer ${env.RESEND_API_KEY}`,
        "content-type": "application/json",
      },
      body: JSON.stringify({
        from: env.RESEND_FROM,
        // ALERT_TO, never the report recipients: operational noise must not
        // reach the people who receive the daily report.
        to: env.ALERT_TO.split(",").map((address) => address.trim()).filter(Boolean),
        subject: mail.subject,
        text: mail.body,
      }),
    });
    if (!response.ok) {
      return `not sent: Resend returned ${response.status}: ${(await response.text()).slice(0, 300)}`;
    }
    return "sent";
  } catch (error) {
    return `not sent: ${String(error)}`;
  }
}

async function runHeartbeat(env: Env): Promise<void> {
  let state: HeartbeatState;
  try {
    state = await readHeartbeatState(env);
  } catch (error) {
    // D1 unreachable is its own outage, and the corpus may be perfectly fine.
    // Log it; do not mail a stall that has not been shown to exist.
    console.error(`heartbeat: could not read D1: ${String(error)}`);
    return;
  }

  const today = taipeiDate(new Date());
  const verdict = assess(state, today);
  console.log(
    `heartbeat: newest=${state.newest ?? "none"} today=${today} ` +
      `behind=${verdict.daysBehind} stale=${verdict.stale}`,
  );
  const mail = renderHeartbeat(verdict, state, today);
  if (!mail) return;

  const outcome = await sendAlertMail(env, mail);
  const line = `heartbeat: ${mail.subject} -- ${outcome}`;
  if (outcome === "sent") console.log(line);
  else console.error(line);
}

/**
 * Report yesterday's (UTC) client token usage when it crossed a threshold, and drop
 * counters that are no longer needed. Never throws, like the heartbeat. Only token
 * labels and counts are read; the usage table holds nothing else.
 */
async function runUsageCheck(env: Env): Promise<void> {
  const now = new Date();
  const day = new Date(now.getTime() - 86_400_000).toISOString().slice(0, 10);
  try {
    const { results } = await env.DB.prepare(
      `SELECT t.label, t.rate_per_day, u.count, u.rejected
         FROM token_usage u JOIN tokens t ON t.token_sha256 = u.token_sha256
        WHERE u.bucket = ?
        ORDER BY t.label`,
    )
      .bind(`d:${day}`)
      .all<{ label: string; rate_per_day: number | null; count: number; rejected: number }>();
    const usage = results.map((row) => ({
      label: row.label,
      calls: Number(row.count),
      rejected: Number(row.rejected),
      perDay: limitsFor(row).perDay,
    }));
    console.log(
      `usage: day=${day} tokens=${usage.length} calls=${usage.reduce((n, u) => n + u.calls, 0)} ` +
        `rejected=${usage.reduce((n, u) => n + u.rejected, 0)}`,
    );
    const mail = renderUsageAlert(day, usage);
    if (mail) {
      const outcome = await sendAlertMail(env, mail);
      (outcome === "sent" ? console.log : console.error)(`usage: ${mail.subject} -- ${outcome}`);
    }

    const today = now.toISOString().slice(0, 10);
    const oldest = new Date(now.getTime() - USAGE_RETENTION_DAYS * 86_400_000).toISOString().slice(0, 10);
    await env.DB.prepare(
      `DELETE FROM token_usage
        WHERE (bucket LIKE 'm:%' AND bucket < ?) OR (bucket LIKE 'd:%' AND bucket < ?)`,
    )
      .bind(`m:${today}`, `d:${oldest}`)
      .run();
  } catch (error) {
    console.error(`usage: check failed: ${String(error)}`);
  }
}

/**
 * GET reports the verdict and sends nothing. POST sends a test mail, labelled as
 * one, whatever the verdict says -- the point is to prove the mail path on a day
 * when the corpus is healthy, which is every day the alarm is not needed.
 */
async function handleHeartbeatProbe(request: Request, env: Env, caller: Caller): Promise<Response> {
  let state: HeartbeatState;
  try {
    state = await readHeartbeatState(env);
  } catch (error) {
    return Response.json({ error: `could not read D1: ${String(error)}` }, { status: 502 });
  }
  const today = taipeiDate(new Date());
  const verdict = assess(state, today);
  const mail = renderHeartbeat(verdict, state, today);
  const body: Json = {
    today_taipei: today,
    newest_report: state.newest,
    corpus_days: state.totalDays,
    days_behind: verdict.daysBehind,
    stale: verdict.stale,
    reason: verdict.reason,
    // Whether the alarm can speak, without disclosing what it was told.
    alerting_configured: Boolean(env.RESEND_API_KEY && env.RESEND_FROM && env.ALERT_TO),
    would_send: mail ? mail.subject : null,
  };

  if (request.method === "GET") return Response.json(body);
  if (request.method !== "POST") {
    return new Response("method not allowed", { status: 405, headers: { allow: "GET, POST" } });
  }

  const outcome = await sendAlertMail(env, {
    subject: "[threat-pulse] heartbeat test, no action needed",
    body: [
      `This is a test of the heartbeat alarm, sent on request by ${caller.label}.`,
      "Nothing is wrong. It exists so the mail path can be proved on a healthy day,",
      "because the real alarm fires only when the collector has already stopped --",
      "which would otherwise make the day it is most needed the first time it ran.",
      "",
      `Corpus right now: newest report ${state.newest ?? "none"}, ${state.totalDays} days held.`,
      `Today in Taipei is ${today}; the alarm reads that as ${verdict.reason}.`,
      "",
      mail
        ? `A real alert would be sent now, with the subject: ${mail.subject}`
        : "No real alert is due.",
    ].join("\n"),
  });
  body.test_send = outcome;
  console.log(`heartbeat: test send by ${caller.label} -- ${outcome}`);
  return Response.json(body, { status: outcome === "sent" ? 200 : 502 });
}

export default {
  async scheduled(_event: ScheduledController, env: Env, ctx: ExecutionContext): Promise<void> {
    ctx.waitUntil(runHeartbeat(env));
    ctx.waitUntil(runUsageCheck(env));
  },

  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);

    if (url.pathname === "/health") {
      return Response.json({ ok: true, server: "iocs" });
    }

    // An alarm that has never fired is an alarm nobody knows works, and this one
    // fires only when the collector has already stopped -- so it would first be
    // exercised on the day it is most needed. GET reports what the cron would
    // decide right now and sends nothing; POST sends a labelled test so the mail
    // path itself can be proved on a healthy day.
    //
    // The recipient is ALERT_TO, read from the Worker's own secrets. A caller
    // cannot name one, so a leaked token cannot turn this into a way to mail
    // anyone but the operator.
    if (url.pathname === "/heartbeat") {
      const caller = await authenticate(request, env);
      if (!caller) {
        return new Response("unauthorized", {
          status: 401,
          headers: { "www-authenticate": 'Bearer realm="iocs"' },
        });
      }
      // Counted like a tool call: POST sends mail, and a leaked token should not be
      // able to send it without limit, even to the operator.
      const refused = await enforceQuota(env, caller);
      if (refused) return refused;
      return handleHeartbeatProbe(request, env, caller);
    }

    if (url.pathname !== "/mcp") {
      return new Response("not found", { status: 404 });
    }
    if (request.method !== "POST") {
      return new Response("method not allowed", { status: 405, headers: { allow: "POST" } });
    }

    const caller = await authenticate(request, env);
    if (!caller) {
      return Response.json(
        { error: "unauthorized" },
        { status: 401, headers: { "www-authenticate": "Bearer" } },
      );
    }

    const tooLarge = () =>
      rpcError(null, -32600, `request body exceeds ${MAX_BODY_BYTES} bytes`, 413);
    if (Number(request.headers.get("content-length") ?? "0") > MAX_BODY_BYTES) return tooLarge();
    let body: Json;
    try {
      // Read as text first: the content-length header is optional and can lie.
      const raw = await request.text();
      if (new TextEncoder().encode(raw).length > MAX_BODY_BYTES) return tooLarge();
      body = JSON.parse(raw) as Json;
    } catch {
      return rpcError(null, -32700, "parse error");
    }
    const id = body.id ?? null;
    const method = String(body.method ?? "");
    const params = (body.params ?? {}) as Json;

    // Only tool calls are counted. MCP clients may initialize and list tools before
    // every call, and neither reads the corpus.
    if (method === "tools/call") {
      const refused = await enforceQuota(env, caller, id);
      if (refused) return refused;
    }

    switch (method) {
      case "initialize":
        return rpcResult(id, {
          protocolVersion: PROTOCOL_VERSION,
          capabilities: { tools: {} },
          serverInfo: { name: "iocs", version: "1.0.0" },
          instructions:
            "Confirmed IoCs from daily SOC reports, with the action and reason this " +
            "project derived and the source article for each. Read-only; no live " +
            "scraping. Use lookup_iocs for the values pulled out of a log.",
        });
      case "notifications/initialized":
        return new Response(null, { status: 202 });
      case "tools/list":
        return rpcResult(id, { tools: TOOLS });
      case "tools/call": {
        const name = String((params.name as string) ?? "");
        const args = (params.arguments ?? {}) as Json;
        try {
          const result = await callTool(name, args, env, caller);
          const isError = Boolean((result as Json).error) || (result as Json).status === "failed";
          // Indented only for the small tools a person reads. An enrichment answer
          // can be 400 KiB, and indenting it is CPU spent on whitespace a machine
          // client discards -- which matters on a plan with a 10 ms CPU limit.
          const indent = name === "enrich_observables" ? undefined : 2;
          return rpcResult(id, {
            content: [{ type: "text", text: JSON.stringify(result, null, indent) }],
            // A tool with an output schema returns its result as structured data
            // too, so a caller need not parse the text. An argument error is not a
            // result and carries only the message.
            ...(name === "enrich_observables" && !(result as Json).error ? { structuredContent: result } : {}),
            isError,
          });
        } catch (error) {
          return rpcResult(id, {
            content: [{ type: "text", text: `tool ${name} failed: ${String(error)}` }],
            isError: true,
          });
        }
      }
      default:
        return rpcError(id, -32601, `method not found: ${method}`);
    }
  },
};
